use std::process::ExitCode;

use neptune_lang::FsLoader;

fn usage() -> ExitCode {
    eprintln!(
        "NeptuneBASIC {}

usage:
  neptune run <file>      compile and run a program
                          (--quality low|medium|high|ultra|auto: where it starts,
                          auto steps down while the game runs slowly;
                          --max-quality <level>: a ceiling for old PCs that
                          the program cannot go over;
                          --render-scale <0.25-1>: draw the 3D view at a
                          lower resolution, for slow graphics cards;
                          --uncapped: no vsync or 60 Hz limit, for benchmarks;
                          --players <n>: start n copies, to test multiplayer)
  neptune check <file>    compile only and report diagnostics
  neptune build <file>    make a stand-alone game (-o <dir>, default dist/<name>;
                          --console keeps the console window on Windows)
  neptune kit             pack this neptune and the IDE into one folder
                          (-o <dir>, default dist/NeptuneBASIC-<os>;
                          use a release build)
  neptune disasm <file>   show generated bytecode
  neptune bench [folder]  run the benchmarks and write docs/BENCHMARKS.md
                          (-o <file>, --only <name>, --runs <n>;
                          use a release build)
  neptune lsp             language server for editors (stdin/stdout)
  neptune dap             debugger for editors (--port <n>; prints the port)
  neptune plugins         list loaded plugins and their commands
  neptune commands        list available commands",
        env!("CARGO_PKG_VERSION")
    );
    ExitCode::from(2)
}

/// `--players n`: runs n - 1 more copies of the program, a second apart so
/// the first has time to start hosting before the others look for a game.
fn start_copies(file: &str, program_args: &[String], players: u32) {
    if players < 2 {
        return;
    }
    std::env::set_var("NEPTUNE_WINDOW_SLOT", "0");
    let Ok(exe) = std::env::current_exe() else { return };
    for i in 1..players {
        let (exe, file, program_args) = (exe.clone(), file.to_string(), program_args.to_vec());
        std::thread::spawn(move || {
            std::thread::sleep(std::time::Duration::from_secs(i as u64));
            let copy = std::process::Command::new(exe).arg("run").arg(file).args(program_args).env("NEPTUNE_WINDOW_SLOT", i.to_string()).spawn();
            if let Err(e) = copy {
                eprintln!("error: could not start another copy: {e}");
            }
        });
    }
}

fn load(path: &str) -> Result<neptune_lang::Program, ExitCode> {
    let src = match std::fs::read_to_string(path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error: cannot read '{path}': {e}");
            return Err(ExitCode::from(1));
        }
    };
    neptune_runtime::compile_source(path, &src, &mut FsLoader).map_err(|e| {
        eprint!("{e}");
        ExitCode::from(1)
    })
}

/// Shows an error of a packaged game on stderr and in a dialog box (the game
/// may have no console): a message box on Windows, zenity or kdialog on
/// Linux, a system alert on macOS.
fn report(msg: &str) {
    eprintln!("{msg}");
    #[cfg(target_os = "macos")]
    {
        let script = format!("display alert \"Game error\" message {:?} as critical", msg.trim_end());
        let _ = std::process::Command::new("osascript").args(["-e", &script]).status();
    }
    #[cfg(all(unix, not(target_os = "macos")))]
    {
        let text = msg.trim_end();
        let shown = std::process::Command::new("zenity")
            .args(["--error", "--title=Game error", "--no-markup", "--text", text])
            .status()
            .is_ok_and(|s| s.success());
        if !shown {
            let _ = std::process::Command::new("kdialog").args(["--title", "Game error", "--error", text]).status();
        }
    }
    #[cfg(windows)]
    {
        #[link(name = "user32")]
        extern "system" {
            fn MessageBoxW(hwnd: *mut core::ffi::c_void, text: *const u16, caption: *const u16, kind: u32) -> i32;
        }
        let wide = |s: &str| s.encode_utf16().chain(std::iter::once(0)).collect::<Vec<u16>>();
        let (text, caption) = (wide(msg.trim_end()), wide("Game error"));
        // MB_ICONERROR = 0x10
        unsafe {
            MessageBoxW(std::ptr::null_mut(), text.as_ptr(), caption.as_ptr(), 0x10);
        }
    }
}

/// Runs the program embedded in this executable (a packaged game).
fn run_embedded(entries: Vec<package::Entry>) -> ExitCode {
    // media paths in the program are relative to the game's folder
    if let Some(dir) = std::env::current_exe().ok().and_then(|e| e.parent().map(|p| p.to_path_buf())) {
        let _ = std::env::set_current_dir(dir);
    }
    let main = entries[0].clone();
    let mut loader = package::BundleLoader { entries };
    let prog = match neptune_runtime::compile_source(&main.key, &main.text, &mut loader) {
        Ok(p) => p,
        Err(e) => {
            report(&e.to_string());
            return ExitCode::from(1);
        }
    };
    match neptune_runtime::run_program(prog) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            report(&e.to_string());
            ExitCode::from(1)
        }
    }
}

// A computer with two graphics cards (most gaming laptops) should run games
// on the fast one. Each system has its own way of asking:
// * Windows: the NVIDIA and AMD drivers look for these two symbols in the
//   executable (exported by build.rs); without them OpenGL programs get the
//   power-saving card.
// * Linux (Mesa): the DRI_PRIME variable, set in `prefer_fast_gpu`.
// * macOS: OpenGL programs get the fast card without asking.
#[cfg(windows)]
#[used]
#[no_mangle]
#[allow(non_upper_case_globals)]
pub static NvOptimusEnablement: u32 = 1;
#[cfg(windows)]
#[used]
#[no_mangle]
#[allow(non_upper_case_globals)]
pub static AmdPowerXpressRequestHighPerformance: u32 = 1;

/// See the comment above. `NEPTUNE_GPU=integrated` keeps the power-saving
/// card on Linux; on Windows that choice is made in the system's graphics
/// settings, which come before a program's own wish.
fn prefer_fast_gpu() {
    #[cfg(target_os = "linux")]
    if std::env::var_os("DRI_PRIME").is_none() && !std::env::var("NEPTUNE_GPU").is_ok_and(|v| v == "integrated") {
        // with one graphics card this changes nothing
        std::env::set_var("DRI_PRIME", "1");
    }
}

fn main() -> ExitCode {
    prefer_fast_gpu();
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    // plugins add commands, so they load before anything is compiled
    let plugin_problems = neptune_runtime::load_plugins();
    if args.first().is_none_or(|a| a != "lsp") {
        for p in &plugin_problems {
            eprintln!("warning: {p}");
        }
    }
    // --quality <level> sets the starting renderer quality for this run
    if let Some(i) = args.iter().position(|a| a == "--quality") {
        let level = args.get(i + 1).cloned().unwrap_or_default();
        if neptune_runtime::quality::parse_level(&level).is_none() && !level.eq_ignore_ascii_case("auto") {
            eprintln!("error: --quality must be low, medium, high, ultra or auto");
            return ExitCode::from(2);
        }
        std::env::set_var("NEPTUNE_QUALITY", &level);
        args.drain(i..=i + 1);
    }
    // --max-quality <level> is a ceiling the program cannot go over (old PCs)
    if let Some(i) = args.iter().position(|a| a == "--max-quality") {
        let level = args.get(i + 1).cloned().unwrap_or_default();
        if neptune_runtime::quality::parse_level(&level).is_none() {
            eprintln!("error: --max-quality must be low, medium, high or ultra");
            return ExitCode::from(2);
        }
        std::env::set_var("NEPTUNE_MAX_QUALITY", &level);
        args.drain(i..=i + 1);
    }
    // --render-scale <0.25-1 or a percentage> draws the 3D view smaller (old PCs)
    if let Some(i) = args.iter().position(|a| a == "--render-scale") {
        let scale = args.get(i + 1).cloned().unwrap_or_default();
        if neptune_runtime::renderscale::parse_scale(&scale).is_none() {
            eprintln!("error: --render-scale must be a number from 0.25 to 1, or a percentage such as 50%");
            return ExitCode::from(2);
        }
        std::env::set_var("NEPTUNE_RENDER_SCALE", &scale);
        args.drain(i..=i + 1);
    }
    // --uncapped runs as fast as the machine allows (benchmarks)
    if let Some(i) = args.iter().position(|a| a == "--uncapped") {
        std::env::set_var("NEPTUNE_UNCAPPED", "1");
        args.remove(i);
    }
    // --players <n> starts more copies, to test multiplayer on one computer
    let mut players = 1;
    if let Some(i) = args.iter().position(|a| a == "--players") {
        players = match args.get(i + 1).and_then(|v| v.parse::<u32>().ok()) {
            Some(n @ 1..=8) => n,
            _ => {
                eprintln!("error: --players must be a number from 1 to 8");
                return ExitCode::from(2);
            }
        };
        args.drain(i..=i + 1);
    }
    if let Some(entries) = package::embedded().filter(|e| !e.is_empty()) {
        // a packaged game: everything after its name is for the program
        neptune_vm::stdlib::set_program_args(args.clone());
        return run_embedded(entries);
    }
    if args.first().is_some_and(|a| a == "plugins") {
        let loaded = neptune_vm::plugin::loaded();
        if loaded.is_empty() {
            println!("no plugins loaded");
        }
        for (path, cmds) in loaded {
            println!("{path}");
            for c in cmds {
                println!("    {c}");
            }
        }
        println!("plugin folders (*.{}):", neptune_vm::dynlib::extension());
        for d in neptune_vm::plugin::search_dirs() {
            println!("    {}", d.display());
        }
        return ExitCode::SUCCESS;
    }
    if args.first().is_some_and(|a| a == "bench") {
        return bench::run(&args[1..]);
    }
    if args.first().is_some_and(|a| a == "lsp") {
        lsp::run();
        return ExitCode::SUCCESS;
    }
    if args.first().is_some_and(|a| a == "dap") {
        return dap::run(&args[1..]);
    }
    if args.first().is_some_and(|a| a == "kit") {
        let out = args.iter().position(|a| a == "-o").and_then(|i| args.get(i + 1)).map(String::as_str);
        return match kit::pack_beside_self(out) {
            Ok(dir) => {
                println!("packed {}", dir.display());
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("error: {e}");
                ExitCode::from(1)
            }
        };
    }
    if args.first().is_some_and(|a| a == "build") {
        let Some(file) = args.get(1) else { return usage() };
        let out = args.iter().position(|a| a == "-o").and_then(|i| args.get(i + 1)).map(String::as_str);
        let console = args.iter().any(|a| a == "--console");
        return match package::build(file, out, console) {
            Ok(exe) => {
                println!("built {}", exe.display());
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprint!("{e}");
                if !e.ends_with('\n') {
                    eprintln!();
                }
                ExitCode::from(1)
            }
        };
    }
    let (cmd, file) = match args.as_slice() {
        [c] if c == "commands" => ("commands", None),
        [c, f, ..] if matches!(c.as_str(), "run" | "check" | "disasm") => (c.as_str(), Some(f.as_str())),
        [f, ..] if !f.starts_with('-') && f.contains('.') => ("run", Some(f.as_str())),
        _ => return usage(),
    };
    match (cmd, file) {
        ("commands", _) => {
            for c in &neptune_runtime::env().commands {
                let params: Vec<String> = c
                    .params
                    .iter()
                    .map(|p| match &p.default {
                        Some(_) => format!("[{}]", p.name),
                        None => p.name.clone(),
                    })
                    .collect();
                println!("{} {}", c.display, params.join(", "));
            }
            ExitCode::SUCCESS
        }
        ("check", Some(f)) => match load(f) {
            Ok(_) => {
                println!("{f}: ok");
                ExitCode::SUCCESS
            }
            Err(c) => c,
        },
        ("disasm", Some(f)) => match load(f) {
            Ok(p) => {
                for i in 0..p.functions.len() {
                    println!("{}", p.disassemble(i as u32));
                }
                ExitCode::SUCCESS
            }
            Err(c) => c,
        },
        ("run", Some(f)) => {
            // the words after the source file are the program's own arguments
            let at = args.iter().position(|a| a == f).map_or(args.len(), |i| i + 1);
            neptune_vm::stdlib::set_program_args(args[at..].to_vec());
            let prog = match load(f) {
                Ok(p) => p,
                Err(c) => return c,
            };
            start_copies(f, &args[at..], players);
            match neptune_runtime::run_program(prog) {
                Ok(()) => ExitCode::SUCCESS,
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        _ => usage(),
    }
}
