"""Writes docs/COMMANDS.md, the command reference, from:

* the command tables (signatures, via list_commands.py),
* docs/commands.txt, the descriptions: `# Category` lines followed by
  `Name: description` lines, and
* docs/examples/*.txt, an example for each command (`=== Name` followed
  by the code; checked by tools/check_doc_examples.py).

Modern names (`ALIASES`) are listed with the command they stand for.

    python tools/gen_reference.py           write docs/COMMANDS.md
    python tools/gen_reference.py --check   only check every command has a description

Every new command needs a line in docs/commands.txt (the language test
`every_command_is_documented` checks this too).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from list_commands import ROOT, commands  # noqa: E402
from check_doc_examples import read_examples  # noqa: E402
import glob  # noqa: E402

DESCRIPTIONS = os.path.join(ROOT, "docs", "commands.txt")
OUT = os.path.join(ROOT, "docs", "COMMANDS.md")
TYPES = {"%": "integer", "#": "float", "$": "string", "?": "any value"}


def read_descriptions():
    cats = []  # [(category, [(name, text)])]
    with open(DESCRIPTIONS, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("# "):
                cats.append((line[2:].strip(), []))
            elif ":" in line and line.strip() and not line.startswith(";"):
                name, text = line.split(":", 1)
                if not cats:
                    cats.append(("Other", []))
                cats[-1][1].append((name.strip(), text.strip()))
    return cats


def basic_signature(sig):
    """`%LoadMesh$file%parent=0` -> ("LoadMesh(file$, [parent%=0])", "integer")."""
    ret = TYPES.get(sig[0]) if sig[0] in TYPES else None
    body = sig[1:] if ret else sig
    m = re.match(r"([A-Za-z_]\w*)(.*)", body)
    name, rest = m.group(1), m.group(2)
    params = []
    for tag, pname, default in re.findall(r'([%#$?])(\w+)(?:=("[^"]*"|[^%#$?]*))?', rest):
        shown = pname + ("" if tag == "?" else tag)
        params.append(f"[{shown}={default}]" if default != "" else shown)
    args = ", ".join(params)
    call = f"{name}({args})" if ret else (f"{name} {args}" if args else name)
    return call, ret


def anchor(name):
    return name.lower()


def main():
    check_only = "--check" in sys.argv
    rows = commands()
    table = {r[1]: r[2] for r in rows if not r[3]}
    aliases = [(r[1], r[3]) for r in rows if r[3]]
    cats = read_descriptions()
    described = {}
    for cat, items in cats:
        for name, text in items:
            if name in described:
                print(f"{name}: described twice", file=sys.stderr)
            described[name] = (cat, text)
    missing = sorted(set(table) - set(described))
    unknown = sorted(set(described) - set(table))
    for n in missing:
        print(f"{n}: no description in docs/commands.txt", file=sys.stderr)
    for n in unknown:
        print(f"{n}: described but not a command", file=sys.stderr)
    if missing or unknown:
        sys.exit(1)
    examples = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "docs", "examples", "*.txt"))):
        for name, code in read_examples(path).items():
            if name not in table:
                print(f"{name}: example in {os.path.basename(path)} but not a command", file=sys.stderr)
                sys.exit(1)
            examples[name] = code
    if check_only:
        print(f"all {len(table)} commands are described, {len(examples)} have examples")
        return

    out = []
    out.append("# Command reference\n")
    out.append(
        "Every NeptuneBASIC command, grouped by area. Generated by "
        "`python tools/gen_reference.py` from the command tables and "
        "[commands.txt](commands.txt); edit that file, not this one.\n"
    )
    out.append(
        "**Reading the entries:** a command that returns a value is shown "
        "as a function call, `Name(a, b)`, with the type it returns. Other "
        "commands are statements, `Name a, b`. A parameter's type is shown "
        "by the mark after its name: `%` a whole number, `#` a number with "
        "a fractional part, `$` text. Optional parameters are in brackets "
        "with their default value. **(ext)** marks commands NeptuneBASIC "
        "adds to the classic command set. Every entry has an example. "
        "To learn the language itself (`If`, `Type`, `Function`, ...), "
        "read [the manual](MANUAL.md).\n"
    )
    total = sum(len(items) for _, items in cats)
    out.append(f"{total} commands and {len(aliases)} modern names.\n")
    out.append("## Contents\n")
    for cat, items in cats:
        out.append(f"* [{cat}](#{re.sub(r'[^a-z0-9 -]', '', cat.lower()).replace(' ', '-')}) ({len(items)})")
    out.append("* [Modern names](#modern-names)\n")
    for cat, items in cats:
        out.append(f"## {cat}\n")
        for name, text in items:
            call, ret = basic_signature(table[name])
            ext = text.startswith("(ext)")
            body = text[5:].strip() if ext else text
            out.append(f"### {name}\n")
            out.append(f"`{call}`" + (f" → {ret}" if ret else "") + "\n")
            out.append(("**(ext)** " if ext else "") + body + "\n")
            if name in examples:
                out.append("```basic\n" + examples[name] + "\n```\n")
    out.append("## Modern names\n")
    out.append(
        "These names do the same as the classic command they stand for "
        "(both can be used).\n"
    )
    out.append("| Modern name | Same as |")
    out.append("|---|---|")
    for alias, target in sorted(aliases):
        out.append(f"| {alias} | [{target}](#{anchor(target)}) |")
    out.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}: {total} commands, {len(aliases)} modern names")


if __name__ == "__main__":
    main()
