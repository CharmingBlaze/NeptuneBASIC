//! `neptune` – the NeptuneBASIC command line.
//!
//! ```text
//! neptune run <file.nb>       compile and run (opens a window on Graphics3D)
//!     --quality low|medium|high|ultra   starting graphics quality
//!     --quality auto                    steps down while the game runs slowly
//!     --max-quality <level>             a ceiling the program cannot go over (old PCs: low)
//!     --render-scale <0.25-1>           draw the 3D view at a lower resolution (old PCs: 0.5)
//!     --uncapped                        no vsync or 60 Hz limit (benchmarks)
//!     --players <n>                     start n copies (to test multiplayer)
//! neptune check <file.nb>     compile only, report diagnostics
//! neptune disasm <file.nb>    print the generated bytecode
//! neptune build <file.nb>     make a stand-alone game in dist/<name>/
//!     -o <dir>                          output folder
//!     --console                         keep the console window (Windows)
//! neptune kit                 pack neptune and the IDE into one folder
//!     -o <dir>                          output folder (default dist/NeptuneBASIC-<os>)
//! neptune bench [folder]      run the benchmarks, write docs/BENCHMARKS.md
//!     -o <file>                         report file
//!     --only <name>                     run one benchmark
//!     --runs <n>                        run n times, report medians
//! neptune lsp                 language server on stdin/stdout (for editors)
//! neptune dap [--port n]      debug adapter on a local TCP port (for editors)
//! neptune plugins             list loaded plugins and where they are looked for
//! neptune commands            list every available command
//! neptune <file.nb>           same as `run`
//! ```

mod bench;
mod dap;
use neptune_runtime::json;
mod kit;
mod lsp;
